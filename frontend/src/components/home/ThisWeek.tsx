import { useEffect, useRef } from 'react'
import { useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { Check, RefreshCw } from 'lucide-react'
import SectionHeader from '../ui/SectionHeader'
import {
  useWeekPlan,
  useGenerateDraft,
  useConfirmEntry,
  useSwapEntry,
  useOpenCard,
} from '../../api'
import type { MealPlanEntryDisplay } from '../../api/types'
import { sourceName } from '../../utils/sourceNames'

const DAY_LABELS = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']

const OWN_RECIPE_SOURCES = new Set(['manual', 'ad_hoc'])

function sourceLabel(sourceType: string): string {
  return OWN_RECIPE_SOURCES.has(sourceType) ? 'Your recipes' : sourceName(sourceType)
}

function getCurrentMondayStr(): string {
  const today = new Date()
  const day = today.getDay() // 0=Sun, 1=Mon...6=Sat
  const diff = day === 0 ? -6 : 1 - day
  const monday = new Date(today)
  monday.setDate(today.getDate() + diff)
  const y = monday.getFullYear()
  const m = String(monday.getMonth() + 1).padStart(2, '0')
  const d = String(monday.getDate()).padStart(2, '0')
  return `${y}-${m}-${d}`
}

function addDays(dateStr: string, n: number): string {
  const [y, m, d] = dateStr.split('-').map(Number)
  const date = new Date(y, m - 1, d)
  date.setDate(date.getDate() + n)
  const yr = date.getFullYear()
  const mo = String(date.getMonth() + 1).padStart(2, '0')
  const dy = String(date.getDate()).padStart(2, '0')
  return `${yr}-${mo}-${dy}`
}

export default function ThisWeek() {
  const weekStart = getCurrentMondayStr()
  const navigate = useNavigate()

  const { data: weekData, isLoading } = useWeekPlan(weekStart)
  const { mutate: generateDraft, isError: generateFailed, reset: resetGenerate } = useGenerateDraft()
  const { mutate: confirmEntry } = useConfirmEntry()
  const { mutate: swapEntry } = useSwapEntry()
  const { mutate: openCard } = useOpenCard()

  const hasAutoGenerated = useRef(false)

  useEffect(() => {
    if (!weekData) return
    if (hasAutoGenerated.current) return
    const isEmpty =
      weekData.confirmed_entries.length === 0 &&
      weekData.draft_entries.length === 0
    if (!isEmpty) return
    hasAutoGenerated.current = true
    generateDraft(weekStart)
  }, [weekData, weekStart, generateDraft])

  function handleRetry() {
    resetGenerate()
    generateDraft(weekStart)
  }

  // Build map: date string → entry (confirmed takes precedence over draft for same date)
  const entryByDate = new Map<string, MealPlanEntryDisplay>()
  if (weekData) {
    for (const e of weekData.draft_entries) entryByDate.set(e.date, e)
    for (const e of weekData.confirmed_entries) entryByDate.set(e.date, e)
  }

  const dayDates = Array.from({ length: 7 }, (_, i) => addDays(weekStart, i))

  function handleTileTap(entry: MealPlanEntryDisplay) {
    if (entry.recipe_id) {
      navigate(`/recipes/${entry.recipe_id}`)
      return
    }
    if (entry.catalog_card_id) {
      openCard(
        {
          cardId: entry.catalog_card_id,
          source: entry.display?.source_type ?? '',
          collectionSlug: '',
        },
        { onSuccess: (recipe) => navigate(`/recipes/${recipe.id}`) }
      )
    }
  }

  function handleConfirm(e: React.MouseEvent, entryId: string) {
    e.stopPropagation()
    confirmEntry(entryId)
  }

  function handleSwap(e: React.MouseEvent, entryId: string) {
    e.stopPropagation()
    swapEntry(entryId)
  }

  return (
    <section aria-label="This week">
      <SectionHeader>This week</SectionHeader>

      {generateFailed && (
        <p className="mt-2 text-sm text-text-secondary">
          Could not suggest a week yet.{' '}
          <button onClick={handleRetry} className="text-olive underline">
            Try again
          </button>
        </p>
      )}

      <div className="mt-3">
        {isLoading && (
          <p className="text-sm text-text-secondary">Loading...</p>
        )}

        {!isLoading && (
          <div
            className="flex gap-[10px] overflow-x-auto pb-2 -mx-4 px-4 scrollbar-hide"
            role="list"
            aria-label="This week dinners"
          >
            {dayDates.map((date, i) => {
              const entry = entryByDate.get(date)
              return (
                <DayTile
                  key={date}
                  dayLabel={DAY_LABELS[i]}
                  entry={entry}
                  onTap={handleTileTap}
                  onConfirm={handleConfirm}
                  onSwap={handleSwap}
                />
              )
            })}
          </div>
        )}
      </div>
    </section>
  )
}

interface DayTileProps {
  dayLabel: string
  entry: MealPlanEntryDisplay | undefined
  onTap: (entry: MealPlanEntryDisplay) => void
  onConfirm: (e: React.MouseEvent, entryId: string) => void
  onSwap: (e: React.MouseEvent, entryId: string) => void
}

function DayTile({ dayLabel, entry, onTap, onConfirm, onSwap }: DayTileProps) {
  const isDraft = entry?.status === 'draft'
  const [imageError, setImageError] = useState(false)

  return (
    <div
      role="listitem"
      className={`flex-shrink-0 w-[168px] bg-white rounded-[12px] border border-warm-border overflow-hidden${
        isDraft ? ' opacity-70' : ''
      }${entry ? ' cursor-pointer' : ''}`}
      onClick={() => entry && onTap(entry)}
    >
      {/* Day label */}
      <div className="px-3 pt-2 pb-0.5">
        <p className="text-[11px] font-medium text-text-secondary uppercase tracking-wide">
          {dayLabel}
        </p>
      </div>

      {/* Photo: 4:3, the recipe card's shape */}
      <div className="w-full aspect-[4/3] bg-warm-gray overflow-hidden">
        {entry?.display?.image_url && !imageError ? (
          <img
            src={entry.display.image_url}
            alt={entry.display.name}
            className="w-full h-full object-cover"
            onError={() => setImageError(true)}
          />
        ) : (
          <div className="w-full h-full flex items-center justify-center text-text-tertiary text-xs">
            {entry ? 'No image' : '—'}
          </div>
        )}
      </div>

      {/* Content */}
      <div className="px-3 py-2 space-y-1">
        {entry?.display ? (
          <>
            <p className="text-[13px] font-medium text-text-primary line-clamp-2 leading-tight">
              {entry.display.name}
            </p>
            <p className="text-[11px] text-text-secondary">
              {sourceLabel(entry.display.source_type)}
            </p>
          </>
        ) : (
          <p className="text-[12px] text-text-tertiary">Not planned</p>
        )}
      </div>

      {/* Accept / swap actions (draft only) */}
      {isDraft && entry && (
        <div className="px-3 pb-3 flex gap-2">
          <button
            onClick={(e) => onConfirm(e, entry.id)}
            aria-label="Accept suggestion"
            className="flex items-center justify-center w-11 h-11 rounded-full bg-olive text-white"
          >
            <Check size={14} />
          </button>
          <button
            onClick={(e) => onSwap(e, entry.id)}
            aria-label="Swap suggestion"
            className="flex items-center justify-center w-11 h-11 rounded-full border border-warm-border text-text-secondary"
          >
            <RefreshCw size={14} />
          </button>
        </div>
      )}
    </div>
  )
}
