import { useEffect, useRef, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { Check, ChevronLeft, ChevronRight, RefreshCw } from 'lucide-react'
import PageContainer from '../components/layout/PageContainer'
import PageTitle from '../components/ui/PageTitle'
import {
  useWeekPlan,
  useGenerateDraft,
  useConfirmEntry,
  useSwapEntry,
  useOpenCard,
} from '../api'
import type { MealPlanEntryDisplay } from '../api/types'
import { ownOrSourceName } from '../utils/sourceNames'
import {
  addDays,
  formatMonthDay,
  formatWeekRange,
  mondayOf,
  todayStr,
  weekDates,
  weekdayName,
} from '../utils/week'

/**
 * Plan page: one week of dinners, a day per row.
 *
 * A first working version, built on the endpoints that exist: the week view,
 * draft generation, accept and swap. An empty week that is not in the past
 * fills itself with suggestions. Choosing a specific recipe for a day, removing
 * or moving a meal, other meal types and servings are not here yet.
 */
export default function Plan() {
  const navigate = useNavigate()
  const thisWeek = mondayOf(new Date())
  const today = todayStr()
  const [weekStart, setWeekStart] = useState(thisWeek)

  const { data: week, isLoading, isError, refetch } = useWeekPlan(weekStart)
  const generate = useGenerateDraft()
  const confirm = useConfirmEntry()
  const swap = useSwapEntry()
  const openCard = useOpenCard()

  // What the last accept or swap did, shown once above the list.
  const [notice, setNotice] = useState<string | null>(null)
  // The entry whose accept, swap or open failed, and why.
  const [rowError, setRowError] = useState<{ entryId: string; message: string } | null>(null)

  const isEmpty =
    week !== undefined && week.confirmed_entries.length === 0 && week.draft_entries.length === 0
  const isPastWeek = weekStart < thisWeek

  // An empty week starts filled with suggestions. Once per week per visit, so a
  // failed or empty generation does not loop; the button below retries.
  // The ref is the guard (it holds under StrictMode's double effect); the state
  // copy is what the empty-week card below reads.
  const autoGenerated = useRef(new Set<string>())
  const [attemptedWeeks, setAttemptedWeeks] = useState<string[]>([])
  const generateDraft = generate.mutate
  useEffect(() => {
    if (!isEmpty || isPastWeek || autoGenerated.current.has(weekStart)) return
    autoGenerated.current.add(weekStart)
    setAttemptedWeeks((weeks) => [...weeks, weekStart])
    generateDraft(weekStart)
  }, [isEmpty, isPastWeek, weekStart, generateDraft])

  function goToWeek(next: string) {
    setWeekStart(next)
    setNotice(null)
    setRowError(null)
    generate.reset()
  }

  function failure(entryId: string, fallback: string) {
    return (error: unknown) => {
      const message = error instanceof Error && error.message ? error.message : fallback
      setRowError({ entryId, message })
    }
  }

  function handleAccept(entry: MealPlanEntryDisplay) {
    setNotice(null)
    setRowError(null)
    confirm.mutate(entry.id, {
      onSuccess: (result) => {
        const added = result.grocery_items_added
        setNotice(
          added > 0
            ? `Added ${added} ${added === 1 ? 'item' : 'items'} to your grocery list.`
            : 'Accepted. Nothing new was needed on your grocery list.'
        )
      },
      onError: failure(entry.id, 'Could not accept this one. Try again.'),
    })
  }

  function handleSwap(entry: MealPlanEntryDisplay) {
    setNotice(null)
    setRowError(null)
    swap.mutate(entry.id, {
      onError: failure(entry.id, 'Nothing else to suggest for this day right now.'),
    })
  }

  function handleOpen(entry: MealPlanEntryDisplay) {
    if (entry.recipe_id) {
      navigate(`/recipes/${entry.recipe_id}`)
      return
    }
    if (entry.catalog_card_id) {
      setRowError(null)
      openCard.mutate(
        {
          cardId: entry.catalog_card_id,
          source: entry.display?.source_type ?? '',
          collectionSlug: '',
        },
        {
          onSuccess: (recipe) => navigate(`/recipes/${recipe.id}`),
          onError: failure(entry.id, 'Could not open this recipe. Try again.'),
        }
      )
    }
  }

  // Confirmed takes precedence over a draft on the same day.
  const entryByDate = new Map<string, MealPlanEntryDisplay>()
  if (week) {
    for (const e of week.draft_entries) entryByDate.set(e.date, e)
    for (const e of week.confirmed_entries) entryByDate.set(e.date, e)
  }

  const busyEntryId = confirm.isPending
    ? confirm.variables
    : swap.isPending
      ? swap.variables
      : undefined

  return (
    <PageContainer>
      <div className="py-6 space-y-4">
        <PageTitle>Plan</PageTitle>

        {/* Week switcher */}
        <div className="flex items-center justify-between">
          <button
            onClick={() => goToWeek(addDays(weekStart, -7))}
            aria-label="Previous week"
            className="flex items-center justify-center w-11 h-11 rounded-full border border-warm-border bg-white text-text-secondary"
          >
            <ChevronLeft size={18} />
          </button>
          <div className="text-center">
            <p className="text-[15px] font-medium text-text-primary">
              {weekTitle(weekStart, thisWeek)}
            </p>
            <p className="text-xs text-text-secondary">{formatWeekRange(weekStart)}</p>
          </div>
          <button
            onClick={() => goToWeek(addDays(weekStart, 7))}
            aria-label="Next week"
            className="flex items-center justify-center w-11 h-11 rounded-full border border-warm-border bg-white text-text-secondary"
          >
            <ChevronRight size={18} />
          </button>
        </div>

        {notice && (
          <p role="status" className="text-sm text-olive-dark">
            {notice}
          </p>
        )}

        {isLoading && <p className="text-sm text-text-secondary">Loading...</p>}

        {isError && (
          <p className="text-sm text-text-secondary">
            Could not load this week.{' '}
            <button onClick={() => refetch()} className="text-olive underline">
              Try again
            </button>
          </p>
        )}

        {generate.isPending && (
          <p className="text-sm text-text-secondary">Choosing dinners for this week...</p>
        )}

        {generate.isError && (
          <p className="text-sm text-text-secondary">
            Could not suggest a week yet.{' '}
            <button onClick={() => generate.mutate(weekStart)} className="text-olive underline">
              Try again
            </button>
          </p>
        )}

        {/* Not before the automatic attempt has started: it would flash. */}
        {isEmpty &&
          (isPastWeek || attemptedWeeks.includes(weekStart)) &&
          !generate.isPending &&
          !generate.isError && (
          <div className="bg-white rounded-card border border-warm-border p-4 text-center space-y-3">
            <p className="text-sm text-text-secondary">
              {isPastWeek ? 'Nothing was planned this week.' : 'Nothing planned yet.'}
            </p>
            {!isPastWeek && (
              <button
                onClick={() => generate.mutate(weekStart)}
                className="px-4 py-2 rounded-button bg-olive text-white text-sm font-medium"
              >
                Suggest dinners
              </button>
            )}
          </div>
        )}

        {week && !isEmpty && (
          <ul className="space-y-3" aria-label="Dinners this week">
            {weekDates(weekStart).map((date) => {
              const entry = entryByDate.get(date)
              return (
                <DayRow
                  key={date}
                  date={date}
                  isToday={date === today}
                  entry={entry}
                  busy={entry !== undefined && entry.id === busyEntryId}
                  error={entry && rowError?.entryId === entry.id ? rowError.message : null}
                  onOpen={handleOpen}
                  onAccept={handleAccept}
                  onSwap={handleSwap}
                />
              )
            })}
          </ul>
        )}
      </div>
    </PageContainer>
  )
}

function weekTitle(weekStart: string, thisWeek: string): string {
  if (weekStart === thisWeek) return 'This week'
  if (weekStart === addDays(thisWeek, 7)) return 'Next week'
  if (weekStart === addDays(thisWeek, -7)) return 'Last week'
  return `Week of ${formatMonthDay(weekStart)}`
}

interface DayRowProps {
  date: string
  isToday: boolean
  entry: MealPlanEntryDisplay | undefined
  busy: boolean
  error: string | null
  onOpen: (entry: MealPlanEntryDisplay) => void
  onAccept: (entry: MealPlanEntryDisplay) => void
  onSwap: (entry: MealPlanEntryDisplay) => void
}

function DayRow({ date, isToday, entry, busy, error, onOpen, onAccept, onSwap }: DayRowProps) {
  const [imageError, setImageError] = useState(false)
  const day = weekdayName(date)
  const isDraft = entry?.status === 'draft'
  const display = entry?.display

  // A swap puts a different recipe in the same row: forget the old picture's failure.
  const imageUrl = display?.image_url ?? null
  useEffect(() => setImageError(false), [imageUrl])

  const details = display
    ? [
        ownOrSourceName(display.source_type),
        display.prep_time_minutes ? `${display.prep_time_minutes} min` : null,
      ]
        .filter(Boolean)
        .join(' · ')
    : null

  return (
    <li className="bg-white rounded-card border border-warm-border overflow-hidden">
      <div className="px-3 pt-2.5 flex items-baseline gap-2">
        <p
          className={`text-[11px] font-medium uppercase tracking-wide ${
            isToday ? 'text-olive' : 'text-text-secondary'
          }`}
        >
          {isToday ? `Today · ${day}` : day}
        </p>
        <p className="text-[11px] text-text-tertiary">{formatMonthDay(date)}</p>
      </div>

      {!entry || !display ? (
        <p className="px-3 pt-1 pb-3 text-[13px] text-text-tertiary">Nothing planned</p>
      ) : (
        <div className="p-3 pt-2 flex gap-3">
          <button
            onClick={() => onOpen(entry)}
            aria-label={`Open ${display.name}`}
            className={`flex-shrink-0 w-[112px] aspect-[4/3] rounded-image-card bg-warm-gray overflow-hidden${
              isDraft ? ' opacity-70' : ''
            }`}
          >
            {imageUrl && !imageError ? (
              <img
                src={imageUrl}
                alt=""
                className="w-full h-full object-cover"
                onError={() => setImageError(true)}
              />
            ) : (
              <span className="w-full h-full flex items-center justify-center text-text-tertiary text-xs">
                No image
              </span>
            )}
          </button>

          <div className="min-w-0 flex-1 flex flex-col">
            <button
              onClick={() => onOpen(entry)}
              className={`text-left${isDraft ? ' opacity-70' : ''}`}
            >
              <span className="block text-[14px] font-medium text-text-primary leading-tight line-clamp-2">
                {display.name}
              </span>
              <span className="block mt-0.5 text-[12px] text-text-secondary">{details}</span>
            </button>

            {isDraft ? (
              <div className="mt-auto pt-2 flex gap-2">
                <button
                  onClick={() => onAccept(entry)}
                  disabled={busy}
                  aria-label={`Accept ${day} dinner`}
                  className="flex items-center gap-1.5 px-3 h-9 rounded-button-sm bg-olive text-white text-[13px] font-medium disabled:opacity-50"
                >
                  <Check size={14} />
                  Accept
                </button>
                <button
                  onClick={() => onSwap(entry)}
                  disabled={busy}
                  aria-label={`Swap ${day} dinner`}
                  className="flex items-center gap-1.5 px-3 h-9 rounded-button-sm border border-warm-btn-border text-text-secondary text-[13px] font-medium disabled:opacity-50"
                >
                  <RefreshCw size={14} />
                  Swap
                </button>
              </div>
            ) : (
              <p className="mt-auto pt-2 flex items-center gap-1 text-[12px] text-olive-dark">
                <Check size={13} />
                Planned
              </p>
            )}
          </div>
        </div>
      )}

      {error && (
        <p role="alert" className="px-3 pb-3 text-[12px] text-terra-dark">
          {error}
        </p>
      )}
    </li>
  )
}
